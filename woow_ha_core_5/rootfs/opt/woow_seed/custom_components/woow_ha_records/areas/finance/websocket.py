"""WebSocket commands for the finance Area.

Panel registration and WebSocket API for personal finance tracking.

This module provides the frontend panel and all WebSocket command handlers
for the Ha Finance custom component. It enables personal finance tracking
within Home Assistant, including account management, transaction recording,
recurring plan scheduling, and analytics.

WebSocket Commands
------------------
All commands use the ``ha_finance/`` prefix and are sent via the Home
Assistant WebSocket API.

**Account Query**
    - ``ha_finance/accounts`` -- List all accounts.
    - ``ha_finance/account`` -- Get single account with transactions and plans.

**Transaction CRUD**
    - ``ha_finance/add_transaction`` -- Record a new transaction.
    - ``ha_finance/update_transaction`` -- Modify an existing transaction.
    - ``ha_finance/delete_transaction`` -- Remove a transaction.

**Recurring Plan CRUD**
    - ``ha_finance/add_plan`` -- Create a recurring plan.
    - ``ha_finance/update_plan`` -- Modify a recurring plan.
    - ``ha_finance/delete_plan`` -- Remove a recurring plan.

**Analytics**
    - ``ha_finance/chart_data`` -- Income vs. expenses chart data by month.

**Account Management**
    - ``ha_finance/add_account`` -- Create a new account (config entry).
    - ``ha_finance/update_account`` -- Rename or annotate an account.
    - ``ha_finance/delete_account`` -- Delete an account and its config entry.

Permission Model
----------------
ALL commands are public -- no admin privileges are required. This is an
important distinction from other Home Assistant components that restrict
certain operations to administrators.

Frequency Options
-----------------
Recurring plans support the following frequency values:
    - ``daily``
    - ``weekly``
    - ``monthly``
    - ``yearly``

Day Constraints
---------------
    - For ``monthly`` and ``yearly`` frequencies, ``day`` must be 1--28.
    - For ``weekly`` frequency, ``day`` must be 1--7 (Monday--Sunday).

Home Assistant Bus Events
-------------------------
The following events are fired on the HA event bus by this component:
    - ``ha_finance_transaction_added`` -- A new transaction was recorded.
    - ``ha_finance_recurring_executed`` -- A recurring plan produced a transaction.
    - ``ha_finance_balance_adjusted`` -- An account balance was adjusted.
    - ``ha_finance_low_balance`` -- An account balance dropped below threshold.

Transaction Types
-----------------
    - ``manual`` -- Created by the user through the UI or API.
    - ``recurring`` -- Auto-generated by a recurring plan.
    - ``adjustment`` -- Balance correction or adjustment entry.
"""
