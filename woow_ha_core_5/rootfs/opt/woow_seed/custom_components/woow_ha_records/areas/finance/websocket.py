@websocket_api.websocket_command(
    {
        vol.Required("type"): "woow_ha_records/finance/accounts",
    }
)
@websocket_api.async_response
async def ws_get_accounts(
    hass: HomeAssistant,
    connection: websocket_api.ActiveConnection,
    msg: dict[str, Any],
) -> None:
    """Handle ``ha_finance/accounts`` -- list all accounts.

    WebSocket command
        ``ha_finance/accounts``

    Parameters
        None.

    Returns
        dict: ``{accounts: [{id, name, balance, note}, ...]}``
            A list of every registered account with its current balance.
    """
    store = _get_store(hass)
    await store.async_load()

    accounts = [
        {
            "id": account.id,
            "name": account.name,
            "balance": account.balance,
            "note": account.note,
        }
        for account in store.data.accounts.values()
    ]

    connection.send_result(msg["id"], {"accounts": accounts})


@websocket_api.websocket_command(
    {
        vol.Required("type"): "woow_ha_records/finance/account",
        vol.Required("account_id"): str,
    }
)
@websocket_api.async_response
async def ws_get_account(
    hass: HomeAssistant,
    connection: websocket_api.ActiveConnection,
    msg: dict[str, Any],
) -> None:
    """Handle ``ha_finance/account`` -- get a single account with full details.

    WebSocket command
        ``ha_finance/account``

    Parameters
        account_id (str): The unique identifier of the account.

    Returns
        dict: ``{account: {id, name, balance, note, transactions: [...],
        recurring_plans: [...]}}``
            The account object including its full transaction history and
            all associated recurring plans.

    Errors
        ``not_found`` -- No account exists with the given *account_id*.
    """
    store = _get_store(hass)
    await store.async_load()

    account = store.data.get_account(msg["account_id"])
    if account is None:
        connection.send_error(msg["id"], "not_found", "Account not found")
        return

    result = {
        "account": {
            "id": account.id,
            "name": account.name,
            "balance": account.balance,
            "note": account.note,
            "transactions": [tx.to_dict() for tx in account.transactions],
            "recurring_plans": {
                plan_id: plan.to_dict()
                for plan_id, plan in account.recurring_plans.items()
            },
        }
    }

    connection.send_result(msg["id"], result)


@websocket_api.websocket_command(
    {
        vol.Required("type"): "woow_ha_records/finance/add_transaction",
        vol.Required("account_id"): str,
        vol.Required("amount"): vol.Coerce(float),
        vol.Optional("note", default=""): str,
        vol.Optional("transaction_type", default=TRANSACTION_MANUAL): str,
    }
)
@websocket_api.async_response
async def ws_add_transaction(
    hass: HomeAssistant,
    connection: websocket_api.ActiveConnection,
    msg: dict[str, Any],
) -> None:
    """Handle ``ha_finance/add_transaction`` -- record a new transaction.

    WebSocket command
        ``ha_finance/add_transaction``

    Parameters
        account_id (str): The account to add the transaction to.
        amount (float): Transaction amount (positive for income, negative
            for expenses).
        note (str, optional): Descriptive note. Defaults to ``""``.
        transaction_type (str, optional): One of ``manual``, ``recurring``,
            or ``adjustment``. Defaults to ``"manual"``.

    Returns
        dict: ``{transaction: {...}, balance: float}``
            The newly created transaction object and the updated account
            balance.

    Side Effects
        - Fires the ``ha_finance_transaction_added`` event on the HA bus.
        - Updates the account balance sensor entity.

    Errors
        ``not_found`` -- No account exists with the given *account_id*.
        ``error`` -- Transaction creation failed.
    """
    coordinator = get_coordinator_for_account(hass, msg["account_id"])
    transaction: Transaction | None = None

    if coordinator is None:
        # Fall back to direct store access
        store = _get_store(hass)
        await store.async_load()
        account = store.data.get_account(msg["account_id"])
        if account is None:
            connection.send_error(msg["id"], "not_found", "Account not found")
            return

        transaction = Transaction.create(
            amount=msg["amount"],
            note=msg["note"],
            transaction_type=msg["transaction_type"],
        )
        account.add_transaction(transaction)
        await store.async_save()
    else:
        transaction = await coordinator.async_add_transaction(
            amount=msg["amount"],
            note=msg["note"],
            transaction_type=msg["transaction_type"],
        )

    if transaction is None:
        connection.send_error(msg["id"], "error", "Failed to create transaction")
        return

    connection.send_result(
        msg["id"],
        {"success": True, "transaction": transaction.to_dict()},
    )


@websocket_api.websocket_command(
    {
        vol.Required("type"): "woow_ha_records/finance/update_transaction",
        vol.Required("account_id"): str,
        vol.Required("transaction_id"): str,
        vol.Optional("amount"): vol.Coerce(float),
        vol.Optional("note"): str,
    }
)
@websocket_api.async_response
async def ws_update_transaction(
    hass: HomeAssistant,
    connection: websocket_api.ActiveConnection,
    msg: dict[str, Any],
) -> None:
    """Handle ``ha_finance/update_transaction`` -- modify an existing transaction.

    WebSocket command
        ``ha_finance/update_transaction``

    Parameters
        account_id (str): The account that owns the transaction.
        transaction_id (str): The unique identifier of the transaction.
        amount (float, optional): New transaction amount. If provided, the
            account balance is adjusted by the difference between the new
            and old amounts.
        note (str, optional): New descriptive note.

    Returns
        dict: The updated transaction object (``{success: true}``).

    Side Effects
        - Adjusts the account balance if *amount* is changed.
        - Refreshes the coordinator and sensor entities.

    Errors
        ``not_found`` -- Account or transaction not found.
    """
    store = _get_store(hass)
    await store.async_load()

    account = store.data.get_account(msg["account_id"])
    if account is None:
        connection.send_error(msg["id"], "not_found", "Account not found")
        return

    # Find and update transaction
    transaction = None
    for tx in account.transactions:
        if tx.id == msg["transaction_id"]:
            transaction = tx
            break

    if transaction is None:
        connection.send_error(msg["id"], "not_found", "Transaction not found")
        return

    # Update balance if amount changed
    if "amount" in msg:
        old_amount = transaction.amount
        new_amount = msg["amount"]
        account.balance += (new_amount - old_amount)
        transaction.amount = new_amount

    if "note" in msg:
        transaction.note = msg["note"]

    await store.async_save()

    # Refresh coordinator if available
    coordinator = get_coordinator_for_account(hass, msg["account_id"])
    if coordinator:
        await coordinator.async_refresh()

    connection.send_result(msg["id"], {"success": True})


@websocket_api.websocket_command(
    {
        vol.Required("type"): "woow_ha_records/finance/delete_transaction",
        vol.Required("account_id"): str,
        vol.Required("transaction_id"): str,
    }
)
@websocket_api.async_response
async def ws_delete_transaction(
    hass: HomeAssistant,
    connection: websocket_api.ActiveConnection,
    msg: dict[str, Any],
) -> None:
    """Handle ``ha_finance/delete_transaction`` -- remove a transaction.

    WebSocket command
        ``ha_finance/delete_transaction``

    Parameters
        account_id (str): The account that owns the transaction.
        transaction_id (str): The unique identifier of the transaction to
            delete.

    Returns
        dict: ``{success: true}``

    Side Effects
        - Reverses the balance change that the deleted transaction
          originally caused.
        - Refreshes the coordinator and sensor entities.

    Errors
        ``not_found`` -- Account or transaction not found.
    """
    store = _get_store(hass)
    await store.async_load()

    account = store.data.get_account(msg["account_id"])
    if account is None:
        connection.send_error(msg["id"], "not_found", "Account not found")
        return

    # Find and remove transaction
    transaction = None
    for i, tx in enumerate(account.transactions):
        if tx.id == msg["transaction_id"]:
            transaction = tx
            account.transactions.pop(i)
            break

    if transaction is None:
        connection.send_error(msg["id"], "not_found", "Transaction not found")
        return

    # Reverse the balance change
    account.balance -= transaction.amount
    await store.async_save()

    # Refresh coordinator if available
    coordinator = get_coordinator_for_account(hass, msg["account_id"])
    if coordinator:
        await coordinator.async_refresh()

    connection.send_result(msg["id"], {"success": True})


@websocket_api.websocket_command(
    {
        vol.Required("type"): "woow_ha_records/finance/add_plan",
        vol.Required("account_id"): str,
        vol.Required("title"): str,
        vol.Required("amount"): vol.Coerce(float),
        vol.Required("frequency"): vol.In(FREQUENCY_OPTIONS),
        vol.Required("day"): vol.All(vol.Coerce(int), vol.Range(min=1, max=28)),
        vol.Optional("month", default=1): vol.All(
            vol.Coerce(int), vol.Range(min=1, max=12)
        ),
        vol.Optional("active", default=True): bool,
    }
)
@websocket_api.async_response
async def ws_add_plan(
    hass: HomeAssistant,
    connection: websocket_api.ActiveConnection,
    msg: dict[str, Any],
) -> None:
    """Handle ``ha_finance/add_plan`` -- create a recurring plan.

    WebSocket command
        ``ha_finance/add_plan``

    Parameters
        account_id (str): The account to attach the plan to.
        title (str): Human-readable name for the recurring plan.
        amount (float): Transaction amount applied on each recurrence.
        frequency (str): One of ``daily``, ``weekly``, ``monthly``, or
            ``yearly``.
        day (int): Day of recurrence (1--28). For ``weekly`` frequency,
            represents the weekday (1--7).
        month (int, optional): Month of recurrence (1--12). Only relevant
            for ``yearly`` frequency. Defaults to ``1``.
        active (bool, optional): Whether the plan is active on creation.
            Defaults to ``true``.

    Returns
        dict: ``{plan: {...}}``
            The newly created recurring plan object including its
            generated ``plan_id``.

    Errors
        ``not_found`` -- No account exists with the given *account_id*.
    """
    import uuid

    coordinator = get_coordinator_for_account(hass, msg["account_id"])
    plan_id = f"plan_{uuid.uuid4().hex[:8]}"

    if coordinator is None:
        # Fall back to direct store access
        store = _get_store(hass)
        await store.async_load()
        account = store.data.get_account(msg["account_id"])
        if account is None:
            connection.send_error(msg["id"], "not_found", "Account not found")
            return
        plan = RecurringPlan(
            id=plan_id,
            title=msg["title"],
            amount=msg["amount"],
            frequency=msg["frequency"],
            day=msg["day"],
            month=msg.get("month", 1),
            active=msg.get("active", True),
        )
        account.add_recurring_plan(plan)
        await store.async_save()
    else:
        await coordinator.async_add_recurring_plan(
            plan_id=plan_id,
            title=msg["title"],
            amount=msg["amount"],
            frequency=msg["frequency"],
            day=msg["day"],
            month=msg["month"],
            active=msg["active"],
        )

    connection.send_result(msg["id"], {"success": True, "plan_id": plan_id})


@websocket_api.websocket_command(
    {
        vol.Required("type"): "woow_ha_records/finance/update_plan",
        vol.Required("account_id"): str,
        vol.Required("plan_id"): str,
        vol.Optional("title"): str,
        vol.Optional("amount"): vol.Coerce(float),
        vol.Optional("frequency"): vol.In(FREQUENCY_OPTIONS),
        vol.Optional("day"): vol.All(vol.Coerce(int), vol.Range(min=1, max=28)),
        vol.Optional("month"): vol.All(vol.Coerce(int), vol.Range(min=1, max=12)),
        vol.Optional("active"): bool,
    }
)
@websocket_api.async_response
async def ws_update_plan(
    hass: HomeAssistant,
    connection: websocket_api.ActiveConnection,
    msg: dict[str, Any],
) -> None:
    """Handle ``ha_finance/update_plan`` -- modify a recurring plan.

    WebSocket command
        ``ha_finance/update_plan``

    Parameters
        account_id (str): The account that owns the plan.
        plan_id (str): The unique identifier of the plan.
        title (str, optional): New plan title.
        amount (float, optional): New recurrence amount.
        frequency (str, optional): New frequency (``daily``, ``weekly``,
            ``monthly``, or ``yearly``).
        day (int, optional): New day of recurrence (1--28, or 1--7 for
            weekly).
        month (int, optional): New month of recurrence (1--12).
        active (bool, optional): Enable or disable the plan.

    Returns
        dict: The updated recurring plan object (``{success: true}``).

    Errors
        ``not_found`` -- Account or plan not found.
    """
    coordinator = get_coordinator_for_account(hass, msg["account_id"])

    # Extract update fields
    update_fields = {}
    for field in ["title", "amount", "frequency", "day", "month", "active"]:
        if field in msg:
            update_fields[field] = msg[field]

    if coordinator is None:
        # Fall back to direct store access
        store = _get_store(hass)
        await store.async_load()
        account = store.data.get_account(msg["account_id"])
        if account is None:
            connection.send_error(msg["id"], "not_found", "Account not found")
            return
        plan = account.recurring_plans.get(msg["plan_id"])
        if plan is None:
            connection.send_error(msg["id"], "not_found", "Plan not found")
            return
        for key, value in update_fields.items():
            setattr(plan, key, value)
        await store.async_save()
    else:
        await coordinator.async_update_recurring_plan(msg["plan_id"], **update_fields)

    connection.send_result(msg["id"], {"success": True})


