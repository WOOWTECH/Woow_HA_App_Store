"""The upgrade test's data check of Home-Assistant-Matter-Hub (pipeline release-gating/179).

The Store's upgrade test (Woow_HA_App_Store .addon-sync/upgrade_runtime.py)
runs `seed` on the comparison target and `verify` on the new version, on the
same data directories, from the mock Supervisor's container (172.30.32.2).
Both go through hamh's own REST API (/api/matter/..., /api/system/info),
never its storage files:

seed     a bridge created through POST /api/matter/bridges (what the web UI's
         "create bridge" does), with a unique name, an include filter, icon,
         country code and startup priority; hamh assigns its Matter port. It
         waits until the bridge's Matter node runs and records the node's
         commissioning identity (passcode, discriminator, manual pairing code).
verify   hamh answers as the new version, the bridge is listed once and reads
         back with the same configuration, its Matter node starts again from
         storage with the same commissioning identity, and a configuration
         change still saves and reads back.

Why a bridge and not a paired controller (owner decision, release-gating/179:
pick the minimum viable check): a Matter fabric can only be created by a real
Matter controller commissioning the bridge, which the upgrade test does not
have. What a user loses when hamh's data is lost is (1) the bridge
configuration (BridgeStorage, migrated v1->v5 by the app on every start) and
(2) the Matter node state in matter.js storage, from which the node's
passcode and discriminator come; both live under /config/data
(--storage-location, addon_config). The bridge covers (1); the commissioning
identity, generated by matter.js for the new node and read back on the new
version, covers (2) as far as it can without a fabric.

Migrations: hamh migrates its bridge storage (BridgeStorage.migrate) before
it loads the bridges and serves the API, so a bridge the new version lists
and reads back with all its fields went through the new version's migrations,
and a bridge node that starts again went through matter.js's storage load.

Access: the add-on runs hamh with --http-ip-whitelist=172.30.32.2 and no
basic auth; the hooks run at that address, so no token or HA header is
needed. ADDON_URL is the ingress port the runtime assigns (62000).

The bridge name and the ids are kept in HOOK_STATE_DIR for verify. Each
check goes to $REPORT_DIR/<hook>.json; the hook exits 1 when one fails.
Standard library only (the hooks run on python:3.12-alpine).
"""
from __future__ import annotations

import json
import os
import secrets
import sys
import time
import urllib.error
import urllib.request

# The startup probe already saw the ingress port answer; the API is served by the same server.
READY_TIMEOUT = 180
# A bridge's Matter node starts after hamh loaded Home Assistant's registry.
RUNNING_TIMEOUT = 240
CALL_TIMEOUT = 60
# The configuration seed writes and verify compares (hamh adds id, port, basicInformation and the status fields).
CONFIG_KEYS = ("name", "filter", "icon", "countryCode", "priority")
IDENTITY_KEYS = ("passcode", "discriminator", "manualPairingCode")


class Hamh:
    """hamh's REST API at ADDON_URL."""

    def __init__(self, base: str) -> None:
        self.base = base.rstrip("/")

    def call(self, method: str, path: str, body: object = None, timeout: float = CALL_TIMEOUT) -> tuple[int, object]:
        data = None if body is None else json.dumps(body).encode()
        request = urllib.request.Request(f"{self.base}{path}", data=data, method=method,
                                         headers={"Content-Type": "application/json", "Accept": "application/json"})
        try:
            with urllib.request.urlopen(request, timeout=timeout) as response:
                status, raw = response.status, response.read()
        except urllib.error.HTTPError as error:
            status, raw = error.code, error.read()
        text = raw.decode("utf-8", "replace")
        try:
            return status, json.loads(text) if text else None
        except ValueError:
            return status, text[:300]

    def get(self, path: str) -> object:
        status, body = self.call("GET", path)
        assert status == 200, f"GET {path} answered {status}: {str(body)[:300]}"
        return body

    def wait_ready(self) -> str:
        """GET /api/matter/bridges answers with a list."""
        deadline, last = time.monotonic() + READY_TIMEOUT, ""
        while True:
            try:
                status, body = self.call("GET", "/api/matter/bridges", timeout=15)
                if status == 200 and isinstance(body, list):
                    return f"hamh lists {len(body)} bridge(s) at {self.base}/api/matter/bridges"
                last = f"HTTP {status}: {str(body)[:200]}"
            except OSError as error:
                last = f"{type(error).__name__}: {str(error)[:200]}"
            if time.monotonic() > deadline:
                raise AssertionError(f"hamh's API did not answer within {READY_TIMEOUT} s: {last}")
            time.sleep(3)

    def wait_running(self, bridge_id: str) -> dict:
        """The bridge's Matter node runs (status running, commissioning data present); its data."""
        deadline, last = time.monotonic() + RUNNING_TIMEOUT, ""
        while True:
            status, body = self.call("GET", f"/api/matter/bridges/{bridge_id}")
            if status == 200 and isinstance(body, dict):
                if body.get("status") == "running" and isinstance(body.get("commissioning"), dict):
                    return body
                last = f"status {body.get('status')!r} ({body.get('statusReason') or 'no reason'})"
                assert body.get("status") != "failed", f"bridge {bridge_id} failed: {body.get('statusReason')}"
            else:
                last = f"HTTP {status}: {str(body)[:200]}"
            if time.monotonic() > deadline:
                raise AssertionError(f"bridge {bridge_id} did not run within {RUNNING_TIMEOUT} s: {last}")
            time.sleep(3)


class Checks:
    """Each check runs even when an earlier one failed, unless it needs what that one made."""

    def __init__(self) -> None:
        self.items: list[dict[str, str]] = []

    def run(self, name: str, check, needs: bool = True) -> object:  # noqa: ANN001 - any callable
        if not needs:
            self.items.append({"name": name, "result": "skip", "detail": "an earlier check it needs failed"})
            return None
        try:
            value = check()
        except Exception as error:  # noqa: BLE001 - every failure is a failed check with its reason
            self.items.append({"name": name, "result": "fail", "detail": f"{type(error).__name__}: {error}"[:500]})
            print(f"FAIL {name}: {error}", flush=True)
            return None
        detail = value if isinstance(value, str) else "ok"
        self.items.append({"name": name, "result": "pass", "detail": detail})
        print(f"pass {name}: {detail}", flush=True)
        return value if value is not None else True

    def finish(self, hook: str) -> int:
        with open(os.path.join(os.environ["REPORT_DIR"], f"{hook}.json"), "w", encoding="utf-8") as f:
            json.dump({"checks": self.items}, f, indent=1)
        return 1 if any(c["result"] != "pass" for c in self.items) else 0


def state_path() -> str:
    return os.path.join(os.environ["HOOK_STATE_DIR"], "hamh-seed.json")


def identity(data: dict) -> dict:
    commissioning = data.get("commissioning") or {}
    return {k: commissioning.get(k) for k in IDENTITY_KEYS}


def seed() -> int:
    hamh, checks = Hamh(os.environ["ADDON_URL"]), Checks()
    marker = secrets.token_hex(4)
    config = {
        "name": f"Woow upgrade {marker}",
        "filter": {"include": [{"type": "pattern", "value": f"input_boolean.woow_upgrade_{marker}_*"}],
                   "exclude": [{"type": "entity_category", "value": "diagnostic"}], "includeMode": "any"},
        "icon": "switch",
        "countryCode": "TW",
        "priority": 42,
    }
    state: dict[str, object] = {"marker": marker, "config": config}
    ready = checks.run("hamh API ready", hamh.wait_ready)

    def create() -> str:
        before = hamh.get("/api/matter/bridges")
        assert not any(b.get("name") == config["name"] for b in before), f"{config['name']} exists before seed"
        status, body = hamh.call("POST", "/api/matter/bridges", config, timeout=RUNNING_TIMEOUT)
        assert status == 200 and isinstance(body, dict) and body.get("id"), f"POST /api/matter/bridges answered {status}: {str(body)[:300]}"
        state["id"], state["port"] = body["id"], body.get("port")
        read = hamh.get(f"/api/matter/bridges/{body['id']}")
        wrong = {k: read.get(k) for k in CONFIG_KEYS if read.get(k) != config[k]}
        assert not wrong, f"the new bridge reads back differently: {wrong}"
        return f"bridge {body['id']} ({config['name']}) on Matter port {body.get('port')}"
    created = checks.run("bridge created", create, bool(ready))

    def running() -> str:
        data = hamh.wait_running(state["id"])
        state["identity"] = identity(data)
        missing = [k for k, v in state["identity"].items() if v in (None, "")]
        assert not missing, f"the running bridge has no {missing} in its commissioning data"
        return (f"Matter node runs, uncommissioned={not data['commissioning'].get('isCommissioned')}, "
                f"discriminator {state['identity']['discriminator']}")
    checks.run("bridge node running", running, bool(created))

    def version() -> str:
        info = hamh.get("/api/system/info")
        state["version"] = info.get("version") if isinstance(info, dict) else None
        return f"hamh {state['version']} (ADDON_VERSION {os.environ.get('ADDON_VERSION')})"
    checks.run("hamh version", version, bool(ready))
    with open(state_path(), "w", encoding="utf-8") as f:
        json.dump(state, f)
    return checks.finish("seed")


def verify() -> int:
    hamh, checks = Hamh(os.environ["ADDON_URL"]), Checks()

    def read_state() -> dict:
        try:
            with open(state_path(), encoding="utf-8") as f:
                loaded = json.load(f)
        except (OSError, ValueError) as error:
            raise AssertionError(f"seed state {state_path()} unreadable (did seed run?): {error}") from error
        assert isinstance(loaded, dict) and loaded.get("id") and loaded.get("identity"), f"seed state incomplete: {sorted(loaded)}"
        return loaded
    state = checks.run("seed state readable", read_state)
    seeded = state is not None
    ready = checks.run("hamh API ready", hamh.wait_ready)

    def version() -> str:
        info = hamh.get("/api/system/info")
        now, expected = (info or {}).get("version"), os.environ.get("ADDON_VERSION", "")
        assert now and expected and str(now).lstrip("v") == expected.lstrip("v"), f"hamh reports version {now!r}, ADDON_VERSION is {expected!r}"
        return f"hamh {state.get('version') if seeded else '?'} -> {now}"
    checks.run("new version serves", version, bool(ready))

    def listed() -> str:
        bridges = hamh.get("/api/matter/bridges")
        same = [b for b in bridges if b.get("id") == state["id"]]
        assert len(same) == 1, f"bridge {state['id']} is listed {len(same)} times among {len(bridges)} bridge(s)"
        return f"bridge {state['id']} listed once among {len(bridges)} bridge(s)"
    is_listed = checks.run("bridge listed", listed, bool(ready) and seeded)

    def kept() -> str:
        read = hamh.get(f"/api/matter/bridges/{state['id']}")
        config = state["config"]
        wrong = {k: [config[k], read.get(k)] for k in CONFIG_KEYS if read.get(k) != config[k]}
        assert not wrong, f"configuration changed (seeded, now): {wrong}"
        assert read.get("port") == state["port"], f"Matter port {state['port']} is now {read.get('port')}"
        return f"name, filter, icon, country code, priority and Matter port {state['port']} read back unchanged"
    checks.run("bridge configuration kept", kept, bool(is_listed))

    def node() -> str:
        data = hamh.wait_running(state["id"])
        now = identity(data)
        assert now == state["identity"], f"commissioning identity changed: seeded {state['identity']}, now {now}"
        return f"Matter node runs again from storage with the same passcode, discriminator {now['discriminator']} and pairing code"
    checks.run("Matter node state kept", node, bool(is_listed))

    def writable() -> str:
        read = hamh.get(f"/api/matter/bridges/{state['id']}")
        # The update schema allows only the configuration keys (additionalProperties: false); seed set no feature flags.
        body = {k: read[k] for k in ("name", "port", "filter") if k in read}
        body.update({k: read[k] for k in ("icon", "countryCode") if read.get(k) is not None})
        body.update({"id": state["id"], "priority": 43})
        status, answer = hamh.call("PUT", f"/api/matter/bridges/{state['id']}", body, timeout=RUNNING_TIMEOUT)
        assert status == 200, f"PUT answered {status}: {str(answer)[:300]}"
        again = hamh.get(f"/api/matter/bridges/{state['id']}")
        assert again.get("priority") == 43, f"priority reads back {again.get('priority')!r} after the update"
        return "a configuration change saves and reads back"
    checks.run("bridge configuration writable", writable, bool(is_listed))
    return checks.finish("verify")


def main(hook: str) -> None:
    sys.exit({"seed": seed, "verify": verify}[hook]())
